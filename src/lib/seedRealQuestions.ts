/**
 * Ensures topics exist under their respective controlled chapters before importing.
 */
export function provisionRequiredTopics(): void {
  const chapters = getSyllabusChapters();

  for (const q of REAL_15_QUESTIONS) {
    const chNameNorm = normalizeSyllabusName(q.chapter);
    const matchedChapter = chapters.find(
      c => normalizeSyllabusName(c.name) === chNameNorm
    );
    if (!matchedChapter) continue;

    const existingTopics = getSyllabusTopics(matchedChapter.id);
    const topNameNorm = normalizeSyllabusName(q.topic);
    const exists = existingTopics.some(
      t => normalizeSyllabusName(t.name) === topNameNorm
    );

    if (!exists) {
      insertSyllabusTopic({
        id: uuid(),
        chapter_id: matchedChapter.id,
        name: q.topic,
        slug: generateSlug(q.topic),
        status: 'active',
        sort_order: existingTopics.length + 1,
        created_at: new Date().toISOString(),
        updated_at: new Date().toISOString(),
      });
    }
  }
}

export function seedRealQuestions(): { imported: number; updated: number } {
  provisionRequiredTopics();

  const existing = getAllQuestions();
  // Check which questions are missing (by ID or exact text match)
  const missing = REAL_15_QUESTIONS.filter(
    q => !existing.some(e => e.id === q.id || e.question_text === q.question_text)
  );

  if (missing.length === 0) {
    // Verify that all present questions have their canonical primary_chapter_id linked
    for (const q of REAL_15_QUESTIONS) {
      const match = existing.find(e => e.id === q.id || e.question_text === q.question_text);
      if (match && !match.primary_chapter_id) {
        importControlledQuestions([q], { allowUntagged: false });
      }
    }
    return { imported: 0, updated: 0 };
  }

  const result = importControlledQuestions(missing, { allowUntagged: false });
  return { imported: result.imported, updated: result.updated };
}
